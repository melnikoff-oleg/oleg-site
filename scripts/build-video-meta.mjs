#!/usr/bin/env node
/**
 * Regenerates src/lib/videos.ts from YouTube itself.
 *
 * Why this file exists: Google's video documentation asks for uploadDate,
 * duration and a stable thumbnail on every VideoObject, and rewards a page that
 * declares its chapters as `hasPart` Clip entries with the "key moments"
 * treatment in search results. All of that is real data about a real video, so
 * it has to come from the video rather than being typed in and left to rot.
 *
 * It also carries the view count, which is the credibility number the page
 * shows a visitor who arrived from a search result and has never heard of Oleg.
 *
 * Uses yt-dlp, not Apify: it is free, local, needs no key, and this is exactly
 * the job it is best at. See CLAUDE.md.
 *
 *   node scripts/build-video-meta.mjs
 *
 * Re-run it when a new video is embedded, or when the view counts have drifted
 * far enough to be worth refreshing. Nothing breaks if it is stale; the numbers
 * simply age.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";

// Every video the site embeds. The slug is only a comment: the pages import by id.
const IDS = [
  ["JhtbnZUU_8E", "claude-reels"],
  ["QoiFASDh8J8", "claude-cowork-outreach"],
  ["AKtT6NLZGoM", "claude-marketing"],
  ["SUZYKyIujQY", "claude-code-instagram"],
  ["QOuH88WW7bQ", "claude-content"],
  ["GK3JFG7x7LA", "claude-social-growth"],
  ["lw69SOTKRM4", "claude-tiktok"],
  ["Jjz4YxtlwHQ", "claude-b2b-outreach"],
  ["mFYKAsGcnso", "5-levels-ai"],
  ["JQQhT0edXXw", "claude-twitter"],
  ["sUqLRKyU0PY", "claude-riemann-hypothesis"],
];

const toSeconds = (stamp) => {
  const parts = stamp.split(":").map(Number);
  return parts.reduce((acc, n) => acc * 60 + n, 0);
};

const out = [];
for (const [id, slug] of IDS) {
  process.stderr.write(`fetching ${id} (${slug})\n`);
  const raw = execFileSync(
    "yt-dlp",
    ["--dump-json", "--no-warnings", `https://www.youtube.com/watch?v=${id}`],
    { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
  );
  const d = JSON.parse(raw);

  // Chapters live in the description as "0:00 - Title" lines. yt-dlp also
  // exposes d.chapters when YouTube has parsed them, so prefer that and fall
  // back to the description.
  let chapters = (d.chapters ?? []).map((c) => ({
    label: c.title.replace(/^[-\s]+/, "").trim(),
    start: Math.round(c.start_time),
  }));
  if (!chapters.length) {
    chapters = [...(d.description ?? "").matchAll(/^(\d{1,2}:\d{2}(?::\d{2})?)\s*[-–—]?\s*(.+)$/gm)]
      .map((m) => ({ label: m[2].trim(), start: toSeconds(m[1]) }))
      .filter((c) => c.label.length > 1);
  }

  const upload = d.upload_date; // YYYYMMDD
  out.push({
    id,
    slug,
    title: d.title,
    views: d.view_count,
    seconds: d.duration,
    uploadDate: `${upload.slice(0, 4)}-${upload.slice(4, 6)}-${upload.slice(6, 8)}`,
    chapters,
  });
}

const today = new Date().toISOString().slice(0, 10);
const body = out
  .map(
    (v) => `  "${v.id}": {
    id: "${v.id}",
    title: ${JSON.stringify(v.title)},
    views: ${v.views},
    seconds: ${v.seconds},
    uploadDate: "${v.uploadDate}",
    chapters: [
${v.chapters.map((c) => `      { label: ${JSON.stringify(c.label)}, start: ${c.start} },`).join("\n")}
    ],
  },`,
  )
  .join("\n");

fs.writeFileSync(
  "src/lib/videos.ts",
  `// GENERATED by scripts/build-video-meta.mjs on ${today}. Do not edit by hand.
//
// Real numbers about real videos, pulled with yt-dlp. Two jobs:
//
// 1. VideoObject structured data. Google asks for uploadDate, duration and a
//    stable thumbnail, and gives "key moments" treatment to a video that
//    declares its chapters. Guessing any of that is how you end up asserting
//    something Google can check and find wrong.
// 2. The credibility line. Someone who arrives from a search result has never
//    heard of Oleg; "48,732 views" is the fastest honest answer to "why should
//    I read this".

export type VideoChapter = { label: string; start: number };

export type VideoMeta = {
  id: string;
  title: string;
  /** View count when the data was last pulled. See VIDEO_STATS_CHECKED. */
  views: number;
  /** Runtime in seconds. */
  seconds: number;
  /** ISO date the video went live on YouTube, NOT the date the page changed. */
  uploadDate: string;
  chapters: VideoChapter[];
};

export const VIDEO_STATS_CHECKED = "${today}";

export const VIDEOS: Record<string, VideoMeta> = {
${body}
};

export function videoMeta(id: string | undefined): VideoMeta | undefined {
  return id ? VIDEOS[id] : undefined;
}

/** ISO 8601 duration, the only format Google accepts on VideoObject.duration. */
export function isoDuration(seconds: number): string {
  const m = Math.floor(seconds / 60);
  const s = seconds % 60;
  return \`PT\${m}M\${s}S\`;
}

/** "16:26", for the runtime chip next to the player. */
export function clock(seconds: number): string {
  const m = Math.floor(seconds / 60);
  const s = seconds % 60;
  return \`\${m}:\${String(s).padStart(2, "0")}\`;
}

/** "122K", for the view-count chip. Full precision reads as false accuracy. */
export function compactViews(n: number): string {
  if (n >= 1_000_000) return \`\${(n / 1_000_000).toFixed(1).replace(/\\.0$/, "")}M\`;
  if (n >= 1_000) return \`\${Math.round(n / 1_000)}K\`;
  return String(n);
}

/** The canonical watch url, optionally deep linked to a second. */
export function watchUrl(id: string, start?: number): string {
  return \`https://www.youtube.com/watch?v=\${id}\${start ? \`&t=\${start}s\` : ""}\`;
}

/**
 * maxresdefault exists for all twelve of these (checked ${today}); it is the
 * only ytimg size that clears Google's thumbnail guidance comfortably.
 */
export function thumbnailUrl(id: string): string {
  return \`https://i.ytimg.com/vi/\${id}/maxresdefault.jpg\`;
}
`,
);
process.stderr.write(`\nwrote src/lib/videos.ts (${out.length} videos)\n`);
