#!/usr/bin/env python3
"""Telegram's "stripped thumbnail": a tiny inline image a page paints (blurred)
before the real file arrives, so a picture's box is never empty.

  python3 scripts/stripped-thumb.py public/preview-poster.jpg
      prints a ~1 KB JPEG data URL, 32 px wide (the homepage video poster).
  python3 scripts/stripped-thumb.py --module public/guide > src/lib/guide-thumbs.ts
      writes every .webp/.png/.jpg in the folder as a ~200-byte WebP data URL,
      keyed by its public path, for the guide figures (src/components/guide.tsx).
"""
import base64, io, sys
from pathlib import Path
from PIL import Image


def thumb(path: Path, width: int, fmt: str, quality: int) -> str:
    im = Image.open(path).convert("RGB")
    im = im.resize((width, max(1, round(im.height * width / im.width))), Image.LANCZOS)
    buf = io.BytesIO()
    im.save(buf, fmt, quality=quality)
    return f"data:image/{fmt.lower()};base64," + base64.b64encode(buf.getvalue()).decode()


if sys.argv[1] == "--module":
    folder = Path(sys.argv[2])
    public = folder.parts.index("public")
    print("// GENERATED by scripts/stripped-thumb.py --module " + sys.argv[2] + ", do not edit.")
    print("// Re-run it after adding or replacing an image in that folder.")
    print("export const THUMBS: Record<string, string> = {")
    for f in sorted(folder.iterdir()):
        if f.suffix.lower() in {".webp", ".png", ".jpg", ".jpeg"}:
            key = "/" + "/".join(f.parts[public + 1 :])
            print(f'  "{key}": "{thumb(f, 24, "WEBP", 40)}",')
    print("};")
else:
    print(thumb(Path(sys.argv[1]), 32, "JPEG", 50))
