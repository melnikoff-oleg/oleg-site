"""Builds the three "30 viral LinkedIn formats" pages from the MS repo.

Reads  ~/Desktop/MS/projects/accounts/oleg_melnikov/research/viral_formats_2026-11-11/
         formats/<niche>.json  (order, format name, why it works, picture and text templates)
         data/<niche>.json     (the posts: author, link, likes, comments, outlier score, date)
         data/thumbs/<id>.jpg  (first picture of each post)
         data/avatars_h/<handle>.jpg  (profile photos, where the author shows one)
Writes src/lib/viral-formats/<niche>.ts and public/viral-formats/<id>.webp

Edit the lists there and re-run:  python3 scripts/build-viral-formats.py
"""
import json, os, re
from PIL import Image

SRC = os.path.expanduser("~/Desktop/MS/projects/accounts/oleg_melnikov/research/viral_formats_2026-11-11")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PUB = os.path.join(ROOT, "public", "viral-formats")
LIB = os.path.join(ROOT, "src", "lib", "viral-formats")
os.makedirs(PUB, exist_ok=True)
os.makedirs(LIB, exist_ok=True)
NAMES = {"Yasin AĞIRBAŞ": "Yasin Ağırbaş", "Okan YILDIZ": "Okan Yıldız", "Tolga YILDIZ": "Tolga Yıldız", "krishna Patwa": "Krishna Patwa"}
MONTHS = "Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec".split()


def short(n):
    return f"{n / 1e6:.1f}M" if n >= 1e6 else (f"{round(n / 1000)}K" if n >= 10000 else f"{n:,}")


def clean_name(s):
    s = re.split(r"\s[-|]\s|,", s)[0]
    s = "".join(ch for ch in s if ch.isalnum() or ch in " .'&()-")
    s = re.sub(r"\s+", " ", s).strip()
    return NAMES.get(s, s)


def avatar(handle):
    """Copies the author's profile photo (if we have one) and returns its file name, else an empty string."""
    src = os.path.join(SRC, "data", "avatars_h", f"{handle}.jpg")
    if not os.path.exists(src):
        return ""
    os.makedirs(os.path.join(PUB, "av"), exist_ok=True)
    im = Image.open(src).convert("RGB")
    im.thumbnail((112, 112))
    im.save(os.path.join(PUB, "av", f"{handle}.webp"), "WEBP", quality=80, method=6)
    return f"{handle}.webp"


total = 0
for niche in ("cyber", "founders", "design"):
    posts = {p["id"]: p for p in json.load(open(os.path.join(SRC, "data", f"{niche}.json")))}
    rows = []
    for f in json.load(open(os.path.join(SRC, "formats", f"{niche}.json"))):
        p = posts[f["id"]]
        im = Image.open(os.path.join(SRC, "data", "thumbs", f"{f['id']}.jpg")).convert("RGB")
        im.save(os.path.join(PUB, f"{f['id']}.webp"), "WEBP", quality=78, method=6)
        y, m, _ = p["d"].split("-")
        score = float(p["score"])
        rows.append({
            "id": f["id"], "name": f["name"], "why": f["why"], "picture": f["picture"], "text": f["text"],
            "author": clean_name(p["name"]), "url": p["url"], "kind": p["type"],
            "likes": f"{p['likes']:,}", "comments": f"{p['comments']:,}", "followers": short(p["followers"]),
            "score": "100x+" if score >= 100 else f"{score:.0f}x" if score >= 10 else f"{score:.1f}x",
            "date": f"{MONTHS[int(m) - 1]} {y}", "width": im.width, "height": im.height,
            "post": re.sub(r"\n{3,}", "\n\n", (p.get("text") or "").replace("\xa0", " ").strip()),
            "headline": re.sub(r"\s+", " ", p.get("headline") or "").strip(), "avatar": avatar(p["handle"]),
        })
    with open(os.path.join(LIB, f"{niche}.ts"), "w") as o:
        o.write("// Generated by scripts/build-viral-formats.py from the MS repo. Edit there and re-run, not here.\n")
        o.write("// Likes, comments and follower counts are as scraped in October and November 2026.\n\n")
        o.write('import type { ViralFormat } from "./types";\n\n')
        o.write("export const FORMATS: ViralFormat[] = " + json.dumps(rows, ensure_ascii=False, indent=2) + ";\n")
    total += len(rows)
print(total, "formats;", sum(os.path.getsize(os.path.join(PUB, x)) for x in os.listdir(PUB)) // 1024, "KB of images")
