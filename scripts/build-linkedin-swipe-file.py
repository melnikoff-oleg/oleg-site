"""Builds /linkedin-swipe-file from the MS repo: the 30 LinkedIn profiles of Oleg's swipe file.

Reads  ~/Desktop/MS/projects/accounts/oleg_melnikov/content/packaging_2026-11-11/assets/profiles.json
       (order, name, followers, headline, link, the "what to take" line) and assets/profiles/<handle>_{banner,photo}.jpg
Writes src/app/linkedin-swipe-file/profiles.ts and public/linkedin-swipe-file/<handle>-{banner,photo}.webp

Edit the list there and re-run:  python3 scripts/build-linkedin-swipe-file.py
"""
import json, os, re
from PIL import Image

SRC = os.path.expanduser("~/Desktop/MS/projects/accounts/oleg_melnikov/content/packaging_2026-11-11/assets")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PUB = os.path.join(ROOT, "public", "linkedin-swipe-file")
os.makedirs(PUB, exist_ok=True)

def followers(n):
    return f"{n / 1e6:.1f}M" if n >= 1e6 else f"{round(n / 1000)}K"

rows = []
for p in json.load(open(os.path.join(SRC, "profiles.json"))):
    h = p["handle"]
    banner = Image.open(os.path.join(SRC, "profiles", f"{h}_banner.jpg")).convert("RGB")
    if banner.width > 1200:
        banner = banner.resize((1200, round(banner.height * 1200 / banner.width)), Image.LANCZOS)
    banner.save(os.path.join(PUB, f"{h}-banner.webp"), "WEBP", quality=80, method=6)
    photo = Image.open(os.path.join(SRC, "profiles", f"{h}_photo.jpg")).convert("RGB")
    photo.thumbnail((192, 192), Image.LANCZOS)
    photo.save(os.path.join(PUB, f"{h}-photo.webp"), "WEBP", quality=82, method=6)
    headline = re.sub(r"\s+", " ", p.get("headline") or "").strip()
    rows.append({"id": h, "name": p["name"], "followers": followers(p["followers"]), "headline": headline,
                 "take": p["copy"], "url": p["url"], "bannerWidth": banner.width, "bannerHeight": banner.height})

out = os.path.join(ROOT, "src", "app", "linkedin-swipe-file", "profiles.ts")
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w") as f:
    f.write("// Generated by scripts/build-linkedin-swipe-file.py from the MS repo. Edit there and re-run, not here.\n")
    f.write("// Follower counts and headlines were read from LinkedIn on 2026-11-11.\n\n")
    f.write("export type SwipeProfile = {\n  id: string;\n  name: string;\n  followers: string;\n  headline: string;\n  take: string;\n  url: string;\n  bannerWidth: number;\n  bannerHeight: number;\n};\n\n")
    f.write("export const PROFILES: SwipeProfile[] = " + json.dumps(rows, ensure_ascii=False, indent=2) + ";\n")
print(len(rows), "profiles;", sum(os.path.getsize(os.path.join(PUB, x)) for x in os.listdir(PUB)) // 1024, "KB of images")
